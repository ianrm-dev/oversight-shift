// Everyday jargon: words a player with no tech, security or AI background might not know.
// Each gets a small hover popover (word + one plain sentence), NOT a Field guide entry: the Field
// guide stays AI-safety terms (glossary.ts). A word that is already a glossary term (compute,
// deployment, audit, sandbox...) links to the glossary instead, so it never appears here.
//
// Matching: `variants` match whole words, case-insensitive unless `exact`. A `pattern` replaces
// the variants when a word is only jargon in some contexts ("live database", not "I live on Elm St").
// `meta` words are linked in briefings, tools, events and the Field guide but not in card content,
// where the same word can mean something ordinary. `auto: false` words are linked only where the
// UI names them on purpose (a label like "Seed" or "Tell").

export interface Jargon {
  id: string;
  /** Display word for the popover heading. */
  word: string;
  /** Forms that appear in game text. */
  variants: string[];
  /** One plain sentence a 14-year-old would understand. */
  plain: string;
  /** Optional everyday comparison. */
  like?: string;
  /** Match case exactly (acronyms like IT, HR). */
  exact?: boolean;
  /** Overrides `variants` for context-limited words. Needs the g flag. */
  pattern?: RegExp;
  /** Not linked inside card content. */
  meta?: boolean;
  /** Only linked by explicit label, never found in running text. */
  auto?: false;
}

